// Run with PGLITE_TEST_MODULE pointing to an isolated @electric-sql/pglite build.
// This harness never connects to Supabase or uses real account data.
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
const {PGlite}=await import(pathToFileURL(process.env.PGLITE_TEST_MODULE).href);
process.on('uncaughtException',error=>{console.error(error.message,error.where||'',error.query?.slice(0,160)||'');process.exit(1)});
const migration=await readFile(new URL('../supabase/migrations/20260928220641_builtin_mission_profiles.sql',import.meta.url),'utf8');
const snapshot=await readFile(new URL('../supabase/migrations/20260827003929_decouple_mission_reward_from_sheet_type.sql',import.meta.url),'utf8');
const admin='00000000-0000-0000-0000-000000000001',existing='00000000-0000-0000-0000-000000000002',fresh='00000000-0000-0000-0000-000000000003';
const schema=`
create role anon; create role authenticated; create role service_role;
create schema auth; create schema private;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
create table public.admin_users(user_id uuid primary key references auth.users);
create table public.google_sheets_user_config(user_id uuid primary key references auth.users on delete cascade,enabled boolean not null default false);
create table public.mission_profiles(id bigint generated by default as identity primary key,user_id uuid not null references auth.users on delete cascade,
 name text not null,description text default '',color text default '#54c27a',multiplier numeric default 2,reward bigint default 0,
 submission_limit integer default 0,network text default 'X',active boolean default true,is_special boolean default false);
create table public.posts(id bigint generated by default as identity primary key,user_id uuid not null references auth.users on delete cascade,
 mission_profile_id bigint,mission_name text,special_reward bigint default 0,sheets_is_special boolean default false,
 published_at date,x_published_at timestamptz,likes bigint default 0,views bigint default 0,closed boolean default false);
create function public.closed_guard() returns trigger language plpgsql as $$begin
 if old.closed and coalesce(current_setting('app.closed_period_internal',true),'')<>'true' then raise exception 'closed'; end if;
 return new; end$$;
create trigger posts_guard_closed_period before update on public.posts for each row execute function public.closed_guard();
alter table public.mission_profiles enable row level security;
create policy own_missions on public.mission_profiles to authenticated using(user_id=auth.uid()) with check(user_id=auth.uid());
grant usage on schema public,private,auth to authenticated;
grant all on public.mission_profiles,public.posts to authenticated;
grant usage on all sequences in schema public to authenticated;
insert into auth.users values('${admin}'),('${existing}'),('${fresh}');
insert into public.admin_users values('${admin}');
insert into public.google_sheets_user_config values('${admin}',true),('${existing}',false);
insert into public.mission_profiles(user_id,name,color,description,reward,is_special) values
 ('${admin}','FOTOS NORMAIS','#0822e7','',0,false),('${admin}','FOTOS HIGH QUALITY','#c400fa','FOTOS DE ALTA QUALIDADE OU EM GRUPO',200,true),
 ('${existing}','Normal antigo','#112233','Minha descrição',0,false),('${existing}','Fotos bônus','#334455','Meu perfil',200,true),
 ('${existing}','Outro bônus antigo','#abcdef','Personalizado',200,false),('${existing}','Vídeo', '#778899','Vídeo',300,true);
insert into public.posts(user_id,mission_profile_id,mission_name,special_reward,sheets_is_special,published_at,likes,views,closed) values
 ('${existing}',3,'Normal antigo',0,false,'2026-09-03',21,300,false),
 ('${existing}',4,'Fotos bônus',200,true,'2026-09-03',42,800,true),
 ('${existing}',5,'Outro bônus antigo',200,false,'2026-08-01',12,400,false),
 ('${fresh}',null,null,0,false,'2026-09-08',90,1000,false);
`;
async function prepare(){const db=new PGlite();await db.exec(schema);await db.exec(snapshot);await db.exec(`
 create trigger snapshot_post_sheet_mission_type before insert or update of mission_profile_id,sheets_is_special on public.posts for each row execute function private.snapshot_post_sheet_mission_type();
 create trigger sync_posts_sheet_mission_type after update of is_special,reward on public.mission_profiles for each row execute function private.sync_posts_sheet_mission_type();
 create function private.protect_mission_special_setting() returns trigger language plpgsql as $$begin return new; end$$;
 create trigger protect_mission_special_setting before insert or update of is_special on public.mission_profiles for each row execute function private.protect_mission_special_setting();
 `);return db;}
const db=await prepare();
const rows=async sql=>(await db.query(sql)).rows;
await db.exec('begin;'+migration+'commit;');
assert.equal((await rows('select count(*)::int n from public.mission_profiles where builtin_kind is not null'))[0].n,6);
assert.deepEqual((await rows(`select id::int,name,color,description,builtin_kind,is_special from public.mission_profiles where user_id='${existing}' order by id`)).slice(0,2),[
 {id:3,name:'FOTOS NORMAIS',color:'#112233',description:'Minha descrição',builtin_kind:'normal',is_special:false},
 {id:4,name:'FOTOS HIGH QUALITY',color:'#334455',description:'Meu perfil',builtin_kind:'hq',is_special:false}
]);
assert.equal((await rows('select count(*)::int n from public.posts where mission_profile_id is null'))[0].n,0);
assert.equal((await rows('select special_reward::int r from public.posts where id=2'))[0].r,200);
assert.equal((await rows('select count(*)::int n from public.mission_profiles where builtin_kind is null'))[0].n,2);
await assert.rejects(db.exec(`update public.mission_profiles set is_special=true where id=3`),/não pode ser uma missão especial/);
await assert.rejects(db.exec(`delete from public.mission_profiles where id=3`),/não excluídos/);
await db.exec(`update public.mission_profiles set name='Nome editado',color='#111111' where id=3`);
await db.exec(`update public.google_sheets_user_config set enabled=true where user_id='${existing}'`);
assert.equal((await rows('select is_special from public.mission_profiles where id=4'))[0].is_special,true);
assert.equal((await rows('select is_special from public.mission_profiles where id=5'))[0].is_special,false);
await db.exec(`select set_config('app.closed_period_internal','true',false);update public.posts set closed=false where id=2;select set_config('app.closed_period_internal','',false);update public.mission_profiles set is_special=false where id=4`);
await db.exec(`update public.google_sheets_user_config set enabled=true where user_id='${existing}'`);
assert.equal((await rows('select is_special from public.mission_profiles where id=4'))[0].is_special,false,'unchanged permission must not overwrite a manual choice');
await db.exec(`update public.google_sheets_user_config set enabled=false where user_id='${existing}'`);
await assert.rejects(db.exec(`update public.mission_profiles set is_special=true where id=4`),/GOOGLE_SHEETS_NOT_ENABLED/);
await db.exec(`select set_config('request.jwt.claim.sub','${existing}',false);set role authenticated;`);
await assert.rejects(db.exec(`update public.mission_profiles set builtin_kind=null where id=3`),/identificação/);
await assert.rejects(db.exec(`insert into public.mission_profiles(user_id,name,builtin_kind) values('${existing}','Falso','normal')`),/identificação/);
await assert.rejects(db.exec(`select private.ensure_builtin_missions('${existing}')`),/permission denied/);
await assert.rejects(db.exec('select * from private.mission_default_templates'),/permission denied/);
assert.equal((await db.query('update public.mission_profiles set name=\'Outro dono\' where id=1 returning id')).rows.length,0);
await db.exec('reset role;');
const signup='00000000-0000-0000-0000-000000000004';
await db.exec(`insert into auth.users values('${signup}');select private.ensure_builtin_missions('${signup}');`);
assert.deepEqual(await rows(`select name,reward::int,is_special,color from public.mission_profiles where user_id='${signup}' order by name`),[
 {name:'FOTOS HIGH QUALITY',reward:200,is_special:false,color:'#c400fa'},
 {name:'FOTOS NORMAIS',reward:0,is_special:false,color:'#0822e7'}
]);
await db.exec(`insert into public.posts(user_id,mission_name) values('${signup}','Sem perfil');`);
assert.equal((await rows(`select mission_name from public.posts where user_id='${signup}'`))[0].mission_name,'FOTOS NORMAIS');
await db.exec(`insert into public.google_sheets_user_config values('${signup}',true);`);
assert.equal((await rows(`select is_special from public.mission_profiles where user_id='${signup}' and builtin_kind='hq'`))[0].is_special,true);
await db.exec(`delete from auth.users where id='${signup}'`);
assert.equal((await rows(`select count(*)::int n from public.mission_profiles where user_id='${signup}'`))[0].n,0,'legitimate account cascade remains possible');
await db.close();
const ambiguous=await prepare();
await ambiguous.exec(`insert into public.posts(user_id,mission_profile_id,published_at) values('${existing}',5,'2026-09-04')`);
await assert.rejects(ambiguous.exec('begin;'+migration+'commit;'),/Perfis ambíguos/);
await ambiguous.exec('rollback');
assert.equal((await ambiguous.query(`select count(*)::int n from information_schema.columns where table_schema='public' and table_name='mission_profiles' and column_name='builtin_kind'`)).rows[0].n,0);
await ambiguous.close();
console.log('PASS: legacy reuse, snapshots, defaults, signup, permission grant/revoke, closed metadata, owner RLS, identity/delete protection, private access, cascade and ambiguous migration rollback.');
