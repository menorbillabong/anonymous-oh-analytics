create or replace function public.admin_delete_closed_period_posts_bulk(
  p_cleanup_ids bigint[],
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_cleanup private.closed_period_post_cleanups%rowtype;
  v_deleted integer;
  v_total_deleted integer := 0;
  v_total_periods integer := 0;
  v_unique_count integer;
  v_existing_count integer;
begin
  if not private.is_admin(v_actor) then
    raise exception 'Administrative access required' using errcode = '42501';
  end if;

  if p_reason is null or char_length(trim(p_reason)) < 3 or char_length(trim(p_reason)) > 500 then
    raise exception 'Administrative reason must contain between 3 and 500 characters';
  end if;

  select count(distinct cleanup_id)::integer
  into v_unique_count
  from unnest(p_cleanup_ids) cleanup_id
  where cleanup_id is not null;

  if coalesce(v_unique_count, 0) < 1 or v_unique_count > 100 then
    raise exception 'Select between 1 and 100 closed periods';
  end if;

  select count(*)::integer
  into v_existing_count
  from private.closed_period_post_cleanups cleanup
  where cleanup.id = any(p_cleanup_ids);

  if v_existing_count <> v_unique_count then
    raise exception 'One or more closed periods were not found' using errcode = 'P0002';
  end if;

  for v_cleanup in
    select cleanup.*
    from private.closed_period_post_cleanups cleanup
    where cleanup.id = any(p_cleanup_ids)
      and cleanup.posts_deleted_at is null
    order by cleanup.id
    for update
  loop
    v_deleted := private.delete_closed_period_posts(v_cleanup.id, 'manual');
    v_total_deleted := v_total_deleted + v_deleted;
    v_total_periods := v_total_periods + 1;

    insert into public.admin_audit_logs (
      admin_user_id,
      target_user_id,
      action,
      reason,
      metadata
    ) values (
      v_actor,
      v_cleanup.user_id,
      'delete_closed_period_posts',
      trim(p_reason),
      jsonb_build_object(
        'cleanup_id', v_cleanup.id,
        'period_start', v_cleanup.period_start,
        'period_end', v_cleanup.period_end,
        'deleted_posts', v_deleted,
        'bulk', true
      )
    );
  end loop;

  return jsonb_build_object(
    'periods', v_total_periods,
    'posts', v_total_deleted
  );
end;
$$;

create or replace function public.admin_dashboard()
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare actor uuid := auth.uid();
begin
  if not private.is_admin(actor) then
    raise exception 'Administrative access required';
  end if;

  return jsonb_build_object(
    'controls', jsonb_build_object(
      'ranking_self_service_enabled', coalesce((select c.ranking_self_service_enabled from public.app_controls c where c.id = 1), false)
    ),
    'cleanup', coalesce((
      select jsonb_build_object(
        'auto_delete_enabled', s.auto_delete_enabled,
        'inactivity_days', s.inactivity_days,
        'grace_days', s.grace_days,
        'updated_at', s.updated_at
      )
      from public.account_cleanup_settings s
      where s.id = 1
    ), jsonb_build_object('auto_delete_enabled', false, 'inactivity_days', 90, 'grace_days', 7)),
    'post_cleanup', coalesce((
      select jsonb_build_object(
        'auto_delete_enabled', settings.auto_delete_enabled,
        'retention_days', settings.retention_days,
        'updated_at', settings.updated_at
      )
      from private.closed_period_post_cleanup_settings settings
      where settings.id = 1
    ), jsonb_build_object('auto_delete_enabled', false, 'retention_days', 40)),
    'users', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', u.id,
        'email', u.email,
        'username', credentials.username_display,
        'display_name', coalesce(u.raw_user_meta_data->>'display_name',''),
        'profile_name', coalesce(s.app_name,''),
        'created_at', u.created_at,
        'last_sign_in_at', u.last_sign_in_at,
        'last_activity_at', private.account_last_activity(u.id),
        'inactive_days', greatest(0, floor(extract(epoch from (now() - private.account_last_activity(u.id))) / 86400))::integer,
        'x_handle', coalesce(s.x_handle,''),
        'cap_unlocked', coalesce(s.cap_unlocked,false),
        'suspended', coalesce(m.suspended,false),
        'suspension_reason', m.suspension_reason,
        'ranking_blocked', coalesce(m.ranking_blocked,false),
        'ranking_control_unlocked', coalesce(m.ranking_control_unlocked,false),
        'is_admin', (a.user_id is not null),
        'deletion_scheduled_at', q.scheduled_at,
        'deletion_execute_after', q.execute_after,
        'deletion_source', q.source,
        'deletion_last_error', q.last_error
      ) order by u.created_at desc)
      from auth.users u
      left join public.username_credentials credentials on credentials.user_id = u.id
      left join public.user_settings s on s.user_id = u.id
      left join public.user_moderation m on m.user_id = u.id
      left join public.admin_users a on a.user_id = u.id
      left join public.account_deletion_queue q on q.user_id = u.id
    ), '[]'::jsonb),
    'posts', coalesce((
      select jsonb_agg(to_jsonb(p) order by p.published_at desc, p.created_at desc)
      from public.posts p
    ), '[]'::jsonb),
    'periods', coalesce((
      select jsonb_agg(to_jsonb(mp) order by mp.month desc)
      from public.mission_periods mp
    ), '[]'::jsonb),
    'closed_periods', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', cleanup.id,
        'archive_id', cleanup.archive_id,
        'user_id', cleanup.user_id,
        'email', u.email,
        'username', credentials.username_display,
        'display_name', coalesce(u.raw_user_meta_data->>'display_name',''),
        'profile_name', coalesce(settings.app_name,''),
        'period_start', cleanup.period_start,
        'period_end', cleanup.period_end,
        'closed_at', cleanup.closed_at,
        'retention_days', cleanup.retention_days,
        'delete_after', cleanup.delete_after,
        'posts_deleted_at', cleanup.posts_deleted_at,
        'posts_deleted_count', cleanup.posts_deleted_count,
        'delete_source', cleanup.delete_source,
        'last_error', cleanup.last_error,
        'remaining_posts', (
          select count(*)::integer
          from public.posts post
          where post.user_id = cleanup.user_id
            and coalesce(
              (post.x_published_at at time zone 'America/Sao_Paulo')::date,
              post.published_at,
              (post.created_at at time zone 'America/Sao_Paulo')::date
            ) between cleanup.period_start and cleanup.period_end
        )
      ) order by cleanup.closed_at desc, cleanup.id desc)
      from private.closed_period_post_cleanups cleanup
      join auth.users u on u.id = cleanup.user_id
      left join public.username_credentials credentials on credentials.user_id = cleanup.user_id
      left join public.user_settings settings on settings.user_id = cleanup.user_id
    ), '[]'::jsonb),
    'logs', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', l.id,
        'admin_email', admin_user.email,
        'target_email', coalesce(target_user.email, l.metadata->>'target_email'),
        'target_username', coalesce(target_credentials.username_display, l.metadata->>'target_username'),
        'action', l.action,
        'reason', l.reason,
        'post_id', l.post_id,
        'created_at', l.created_at
      ) order by l.created_at desc)
      from public.admin_audit_logs l
      join auth.users admin_user on admin_user.id = l.admin_user_id
      left join auth.users target_user on target_user.id = l.target_user_id
      left join public.username_credentials target_credentials on target_credentials.user_id = l.target_user_id
    ), '[]'::jsonb)
  );
end;
$function$;

