create or replace function public.admin_set_closed_period_post_cleanup(
  p_enabled boolean,
  p_retention_days integer
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
begin
  if not private.is_admin(v_actor) then
    raise exception 'Administrative access required' using errcode = '42501';
  end if;

  if p_retention_days is null or p_retention_days < 1 or p_retention_days > 3650 then
    raise exception 'CLOSED_PERIOD_POSTS_INVALID_RETENTION' using errcode = '22023';
  end if;

  insert into private.closed_period_post_cleanup_settings (
    id,
    auto_delete_enabled,
    retention_days,
    updated_at,
    updated_by
  ) values (
    1,
    coalesce(p_enabled, false),
    p_retention_days,
    now(),
    v_actor
  )
  on conflict (id) do update
  set auto_delete_enabled = excluded.auto_delete_enabled,
      retention_days = excluded.retention_days,
      updated_at = excluded.updated_at,
      updated_by = excluded.updated_by;

  insert into public.admin_audit_logs (
    admin_user_id,
    action,
    reason,
    metadata
  ) values (
    v_actor,
    'configure_closed_period_post_cleanup',
    case when coalesce(p_enabled, false)
      then 'Exclusão automática de publicações de novos períodos fechados configurada.'
      else 'Exclusão automática de publicações de novos períodos fechados desativada.'
    end,
    jsonb_build_object(
      'enabled', coalesce(p_enabled, false),
      'retention_days', p_retention_days,
      'applies_to', 'future_closed_periods'
    )
  );
end;
$$;

create or replace function public.admin_schedule_closed_period_posts(
  p_cleanup_id bigint,
  p_enabled boolean,
  p_retention_days integer,
  p_reason text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_cleanup private.closed_period_post_cleanups%rowtype;
  v_delete_after timestamp with time zone;
begin
  if not private.is_admin(v_actor) then
    raise exception 'Administrative access required' using errcode = '42501';
  end if;

  if p_reason is null or char_length(trim(p_reason)) < 3 or char_length(trim(p_reason)) > 500 then
    raise exception 'Administrative reason must contain between 3 and 500 characters';
  end if;

  if coalesce(p_enabled, false)
     and (p_retention_days is null or p_retention_days < 1 or p_retention_days > 3650) then
    raise exception 'CLOSED_PERIOD_POSTS_INVALID_RETENTION' using errcode = '22023';
  end if;

  select cleanup.*
  into v_cleanup
  from private.closed_period_post_cleanups cleanup
  where cleanup.id = p_cleanup_id
  for update;

  if not found then
    raise exception 'CLOSED_PERIOD_POSTS_NOT_FOUND' using errcode = 'P0002';
  end if;

  if v_cleanup.posts_deleted_at is not null then
    raise exception 'CLOSED_PERIOD_POSTS_ALREADY_DELETED' using errcode = 'P0001';
  end if;

  v_delete_after := case when coalesce(p_enabled, false)
    then v_cleanup.closed_at + make_interval(days => p_retention_days)
    else null
  end;

  update private.closed_period_post_cleanups
  set retention_days = case when coalesce(p_enabled, false) then p_retention_days else null end,
      delete_after = v_delete_after,
      last_error = null,
      updated_at = now()
  where id = p_cleanup_id;

  insert into public.admin_audit_logs (
    admin_user_id,
    target_user_id,
    action,
    reason,
    metadata
  ) values (
    v_actor,
    v_cleanup.user_id,
    case when coalesce(p_enabled, false)
      then 'schedule_closed_period_post_cleanup'
      else 'cancel_closed_period_post_cleanup'
    end,
    trim(p_reason),
    jsonb_build_object(
      'cleanup_id', p_cleanup_id,
      'period_start', v_cleanup.period_start,
      'period_end', v_cleanup.period_end,
      'retention_days', case when coalesce(p_enabled, false) then p_retention_days else null end,
      'delete_after', v_delete_after
    )
  );
end;
$$;

