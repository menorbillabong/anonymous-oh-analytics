create or replace function private.delete_closed_period_posts(
  p_cleanup_id bigint,
  p_source text
)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cleanup private.closed_period_post_cleanups%rowtype;
  v_post_ids bigint[];
  v_deleted integer := 0;
begin
  if p_source not in ('manual', 'automatic') then
    raise exception 'CLOSED_PERIOD_POSTS_INVALID_SOURCE' using errcode = '22023';
  end if;

  select cleanup.*
  into v_cleanup
  from private.closed_period_post_cleanups cleanup
  where cleanup.id = p_cleanup_id
  for update;

  if not found then
    raise exception 'CLOSED_PERIOD_POSTS_NOT_FOUND' using errcode = 'P0002';
  end if;

  if v_cleanup.posts_deleted_at is not null then
    return v_cleanup.posts_deleted_count;
  end if;

  select coalesce(array_agg(post.id order by post.id), '{}'::bigint[])
  into v_post_ids
  from public.posts post
  where post.user_id = v_cleanup.user_id
    and coalesce(
      (post.x_published_at at time zone 'America/Sao_Paulo')::date,
      post.published_at,
      (post.created_at at time zone 'America/Sao_Paulo')::date
    ) between v_cleanup.period_start and v_cleanup.period_end;

  if cardinality(v_post_ids) > 0 then
    update public.admin_audit_logs audit
    set metadata = audit.metadata || jsonb_build_object('deleted_post_id', audit.post_id),
        post_id = null
    where audit.post_id = any(v_post_ids);

    delete from public.posts post
    where post.id = any(v_post_ids);

    get diagnostics v_deleted = row_count;
  end if;

  update private.closed_period_post_cleanups
  set posts_deleted_at = now(),
      posts_deleted_count = v_deleted,
      delete_source = p_source,
      last_error = null,
      updated_at = now()
  where id = p_cleanup_id;

  return v_deleted;
end;
$$;

create or replace function private.delete_due_closed_period_posts()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_cleanup_id bigint;
  v_deleted integer := 0;
begin
  for v_cleanup_id in
    select cleanup.id
    from private.closed_period_post_cleanups cleanup
    where cleanup.posts_deleted_at is null
      and cleanup.delete_after is not null
      and cleanup.delete_after <= now()
    order by cleanup.delete_after, cleanup.id
  loop
    begin
      v_deleted := v_deleted + private.delete_closed_period_posts(v_cleanup_id, 'automatic');
    exception
      when others then
        update private.closed_period_post_cleanups
        set last_error = left(sqlerrm, 500),
            updated_at = now()
        where id = v_cleanup_id;
    end;
  end loop;

  return v_deleted;
end;
$$;

