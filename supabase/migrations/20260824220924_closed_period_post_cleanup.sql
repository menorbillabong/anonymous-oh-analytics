-- Configure and execute publication cleanup only for periods that were closed.
-- Cleanup schedules are stored separately so the 40-day archive retention can
-- remain unchanged even when publication retention is longer.

create table if not exists private.closed_period_post_cleanup_settings (
  id smallint primary key default 1 check (id = 1),
  auto_delete_enabled boolean not null default false,
  retention_days integer not null default 40 check (retention_days between 1 and 3650),
  updated_at timestamp with time zone not null default now(),
  updated_by uuid references auth.users(id) on delete set null
);

insert into private.closed_period_post_cleanup_settings (id)
values (1)
on conflict (id) do nothing;

create table if not exists private.closed_period_post_cleanups (
  id bigint generated by default as identity primary key,
  archive_id bigint unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  period_start date not null,
  period_end date not null,
  closed_at timestamp with time zone not null,
  retention_days integer check (retention_days between 1 and 3650),
  delete_after timestamp with time zone,
  posts_deleted_at timestamp with time zone,
  posts_deleted_count integer not null default 0 check (posts_deleted_count >= 0),
  delete_source text check (delete_source in ('manual', 'automatic')),
  last_error text,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  constraint closed_period_post_cleanups_valid_period check (period_end >= period_start)
);

create index if not exists closed_period_post_cleanups_due_idx
  on private.closed_period_post_cleanups (delete_after)
  where posts_deleted_at is null and delete_after is not null;

create index if not exists closed_period_post_cleanups_user_idx
  on private.closed_period_post_cleanups (user_id, closed_at desc);

revoke all on table private.closed_period_post_cleanup_settings from public, anon, authenticated;
revoke all on table private.closed_period_post_cleanups from public, anon, authenticated;

create or replace function private.capture_closed_period_post_cleanup()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_enabled boolean := false;
  v_days integer := 40;
begin
  select settings.auto_delete_enabled, settings.retention_days
  into v_enabled, v_days
  from private.closed_period_post_cleanup_settings settings
  where settings.id = 1;

  insert into private.closed_period_post_cleanups (
    archive_id,
    user_id,
    period_start,
    period_end,
    closed_at,
    retention_days,
    delete_after
  ) values (
    new.id,
    new.user_id,
    new.period_start,
    new.period_end,
    new.archived_at,
    case when coalesce(v_enabled, false) then coalesce(v_days, 40) else null end,
    case when coalesce(v_enabled, false)
      then new.archived_at + make_interval(days => coalesce(v_days, 40))
      else null
    end
  )
  on conflict (archive_id) do nothing;

  return new;
end;
$$;

