create table public.tracking_periods (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  start_date date not null,
  end_date date,
  opened_at timestamptz not null default clock_timestamp(),
  closed_at timestamptz,
  archive_id bigint references public.archived_periods(id) on delete set null,
  constraint tracking_period_dates_valid check (end_date is null or end_date >= start_date),
  constraint tracking_period_close_state_valid check (
    (end_date is null and closed_at is null and archive_id is null)
    or (end_date is not null and closed_at is not null)
  )
);

comment on table public.tracking_periods is
  'Explicit per-user tracking periods. Existing posts are never migrated, deleted, or reassigned automatically.';

create unique index tracking_periods_one_open_per_user_idx
  on public.tracking_periods (user_id)
  where end_date is null;

create index tracking_periods_user_opened_idx
  on public.tracking_periods (user_id, opened_at desc);

