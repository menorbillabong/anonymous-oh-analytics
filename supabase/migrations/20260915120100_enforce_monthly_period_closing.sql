create or replace function public.admin_period_close_cooldown_verified(
  p_actor uuid,
  p_action text,
  p_target_user uuid default null,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_period public.tracking_periods%rowtype;
  v_released_at timestamptz;
  v_release_id bigint;
  v_affected integer;
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
begin
  if not private.is_admin(p_actor) then
    raise exception 'Administrative access required' using errcode = '42501';
  end if;

  if p_action = 'status' then
    return coalesce((
      select jsonb_agg(jsonb_build_object(
        'user_id', period.user_id,
        'last_closed_at', latest.closed_at,
        'next_allowed_at', ((date_trunc('month', period.opened_at at time zone 'America/Sao_Paulo') + interval '1 month') at time zone 'America/Sao_Paulo'),
        'blocked', v_today < (date_trunc('month', period.opened_at at time zone 'America/Sao_Paulo') + interval '1 month')::date
          and individual.released_at is null and global_release.released_at is null,
        'reset_at', coalesce(individual.released_at, global_release.released_at),
        'release_source', case when individual.released_at is not null then 'individual' when global_release.released_at is not null then 'global' end
      ) order by period.opened_at desc)
      from public.tracking_periods period
      left join lateral (
        select max(closed.closed_at) as closed_at
        from public.tracking_periods closed
        where closed.user_id = period.user_id and closed.closed_at is not null
      ) latest on true
      left join lateral (
        select release.released_at
        from private.period_close_individual_releases release
        where release.tracking_period_id = period.id and release.consumed_at is null
        order by release.released_at desc limit 1
      ) individual on true
      left join lateral (
        select release.released_at
        from private.period_close_global_releases release
        where release.released_at >= period.opened_at
          and not exists (
            select 1 from private.period_close_global_consumptions consumption
            where consumption.release_id = release.id and consumption.user_id = period.user_id
          )
        order by release.released_at desc, release.id desc limit 1
      ) global_release on true
      where period.end_date is null
    ), '[]'::jsonb);
  end if;

  if p_action not in ('reset', 'release_all') then
    raise exception 'PERIOD_CLOSE_COOLDOWN_ACTION_INVALID' using errcode = '22023';
  end if;
  if p_reason is null or char_length(trim(p_reason)) < 3 or char_length(trim(p_reason)) > 500 then
    raise exception 'Administrative reason must contain between 3 and 500 characters';
  end if;

  if p_action = 'release_all' then
    select count(*)::integer into v_affected
    from public.tracking_periods period
    where period.end_date is null
      and v_today < (date_trunc('month', period.opened_at at time zone 'America/Sao_Paulo') + interval '1 month')::date
      and not exists (
        select 1 from private.period_close_individual_releases release
        where release.tracking_period_id = period.id and release.consumed_at is null
      )
      and not exists (
        select 1 from private.period_close_global_releases release
        where release.released_at >= period.opened_at
          and not exists (
            select 1 from private.period_close_global_consumptions consumption
            where consumption.release_id = release.id and consumption.user_id = period.user_id
          )
      );
    if v_affected = 0 then
      raise exception 'PERIOD_CLOSE_COOLDOWN_NOT_ACTIVE' using errcode = 'P0001';
    end if;
    insert into private.period_close_global_releases (released_by, reason)
    values (p_actor, trim(p_reason)) returning id, released_at into v_release_id, v_released_at;
    insert into public.admin_audit_logs (admin_user_id, target_user_id, action, reason, metadata)
    values (p_actor, null, 'grant_period_close_global', trim(p_reason), jsonb_build_object(
      'release_id', v_release_id, 'released_at', v_released_at, 'affected_open_periods', v_affected
    ));
    return jsonb_build_object('release_id', v_release_id, 'released_at', v_released_at, 'affected_users', v_affected);
  end if;

  if p_target_user is null or not exists (select 1 from auth.users target where target.id = p_target_user) then
    raise exception 'PERIOD_CLOSE_COOLDOWN_USER_NOT_FOUND' using errcode = 'P0002';
  end if;

  select period.* into v_period
  from public.tracking_periods period
  where period.user_id = p_target_user and period.end_date is null
  for update;

  if v_period.id is null
     or v_today >= (date_trunc('month', v_period.opened_at at time zone 'America/Sao_Paulo') + interval '1 month')::date
     or exists (
       select 1 from private.period_close_individual_releases release
       where release.tracking_period_id = v_period.id and release.consumed_at is null
     )
     or exists (
       select 1 from private.period_close_global_releases release
       where release.released_at >= v_period.opened_at
         and not exists (
           select 1 from private.period_close_global_consumptions consumption
           where consumption.release_id = release.id and consumption.user_id = p_target_user
         )
     ) then
    raise exception 'PERIOD_CLOSE_COOLDOWN_NOT_ACTIVE' using errcode = 'P0001';
  end if;

  insert into private.period_close_individual_releases (tracking_period_id, user_id, released_by, reason)
  values (v_period.id, p_target_user, p_actor, trim(p_reason))
  returning id, released_at into v_release_id, v_released_at;

  insert into public.admin_audit_logs (admin_user_id, target_user_id, action, reason, metadata)
  values (p_actor, p_target_user, 'grant_period_close_individual', trim(p_reason), jsonb_build_object(
    'release_id', v_release_id, 'tracking_period_id', v_period.id,
    'period_start', v_period.start_date, 'released_at', v_released_at
  ));

  return jsonb_build_object('user_id', p_target_user, 'tracking_period_id', v_period.id, 'released_at', v_released_at);
end;
$$;

