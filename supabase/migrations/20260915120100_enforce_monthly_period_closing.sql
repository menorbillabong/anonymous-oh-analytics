-- Replace the legacy seven-day cooldown with calendar-month closing rules.
-- Early releases are scoped to periods that are already open and are consumed once.

create table if not exists private.period_close_individual_releases (
  id bigint generated by default as identity primary key,
  tracking_period_id bigint not null unique references public.tracking_periods(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  released_at timestamptz not null default clock_timestamp(),
  released_by uuid references auth.users(id) on delete set null,
  reason text not null check (char_length(trim(reason)) between 3 and 500),
  consumed_at timestamptz,
  consumed_period_end date
);

create index if not exists period_close_individual_releases_user_idx
  on private.period_close_individual_releases (user_id, released_at desc);

create table if not exists private.period_close_global_releases (
  id bigint generated by default as identity primary key,
  released_at timestamptz not null default clock_timestamp(),
  released_by uuid references auth.users(id) on delete set null,
  reason text not null check (char_length(trim(reason)) between 3 and 500)
);

create table if not exists private.period_close_global_consumptions (
  release_id bigint not null references private.period_close_global_releases(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  tracking_period_id bigint not null references public.tracking_periods(id) on delete cascade,
  consumed_at timestamptz not null default clock_timestamp(),
  consumed_period_end date not null,
  primary key (release_id, user_id)
);

alter table private.period_close_individual_releases enable row level security;
alter table private.period_close_global_releases enable row level security;
alter table private.period_close_global_consumptions enable row level security;

revoke all on table private.period_close_individual_releases from public, anon, authenticated, service_role;
revoke all on table private.period_close_global_releases from public, anon, authenticated, service_role;
revoke all on table private.period_close_global_consumptions from public, anon, authenticated, service_role;

alter table public.tracking_periods
  add column if not exists corrected_at timestamptz,
  add column if not exists correction_count integer not null default 0;

create index if not exists tracking_periods_archive_id_idx
  on public.tracking_periods (archive_id)
  where archive_id is not null;

create or replace function private.enforce_period_close_cooldown()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := auth.uid();
  v_today date := (now() at time zone 'America/Sao_Paulo')::date;
  v_available_on date;
  v_period public.tracking_periods%rowtype;
  v_individual_id bigint;
  v_global_id bigint;
begin
  if v_actor is null or new.user_id <> v_actor then
    raise exception 'ARCHIVED_PERIOD_AUTH_REQUIRED' using errcode = '42501';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(82431, pg_catalog.hashtext(new.user_id::text));

  select period.*
  into v_period
  from public.tracking_periods period
  where period.user_id = new.user_id
    and period.end_date is null
    and period.start_date = new.period_start
  for update;

  if v_period.id is null then
    raise exception 'TRACKING_PERIOD_NOT_OPEN' using errcode = 'P0001';
  end if;

  v_available_on := (date_trunc('month', v_period.opened_at at time zone 'America/Sao_Paulo') + interval '1 month')::date;
  if v_today >= v_available_on then
    return new;
  end if;

  select release.id
  into v_individual_id
  from private.period_close_individual_releases release
  where release.tracking_period_id = v_period.id
    and release.user_id = new.user_id
    and release.consumed_at is null
  for update;

  if v_individual_id is not null then
    update private.period_close_individual_releases
    set consumed_at = clock_timestamp(),
        consumed_period_end = new.period_end
    where id = v_individual_id;
    return new;
  end if;

  select release.id
  into v_global_id
  from private.period_close_global_releases release
  where release.released_at >= v_period.opened_at
    and not exists (
      select 1
      from private.period_close_global_consumptions consumption
      where consumption.release_id = release.id
        and consumption.user_id = new.user_id
    )
  order by release.released_at desc, release.id desc
  limit 1
  for update;

  if v_global_id is not null then
    insert into private.period_close_global_consumptions (
      release_id, user_id, tracking_period_id, consumed_period_end
    ) values (
      v_global_id, new.user_id, v_period.id, new.period_end
    );
    return new;
  end if;

  raise exception 'TRACKING_PERIOD_CLOSE_MONTHLY:%', v_available_on using errcode = 'P0001';
end;
$$;

