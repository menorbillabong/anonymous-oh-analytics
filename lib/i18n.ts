function translateDynamic(value: string, language: Exclude<SiteLanguage, 'pt-BR'>) {
  const replacements: Array<[RegExp, string, string]> = [
    [/^Meta mensal de ([\d.,]+) publicações atingida\.$/, 'Monthly goal of $1 posts reached.', 'Meta mensual de $1 publicaciones alcanzada.'],
    [/^([\d.,]+) vaga\(s\) restante\(s\) neste mês$/, '$1 slot(s) remaining this month', '$1 espacio(s) restante(s) este mes'],
    [/^([\d.,]+) vaga\(s\) restante\(s\) da meta mensal de ([\d.,]+)\.$/, '$1 slot(s) remaining from the monthly goal of $2.', '$1 espacio(s) restante(s) de la meta mensual de $2.'],
    [/^Coletando dados de ([\d.,]+) publicação\(ões\)\.\.\.$/, 'Collecting data from $1 post(s)...', 'Recopilando datos de $1 publicación(es)...'],
    [/^([\d.,]+) publicação\(ões\) atualizada\(s\) com sucesso\.$/, '$1 post(s) updated successfully.', '$1 publicación(es) actualizada(s) correctamente.'],
    [/^([\d.,]+) de ([\d.,]+) publicações atualizadas\.$/, '$1 of $2 posts updated.', '$1 de $2 publicaciones actualizadas.'],
    [/^Ver publicações de (.+)$/, 'View posts from $1', 'Ver publicaciones de $1'],
    [/^Progresso de (.+)$/, '$1 progress', 'Progreso de $1'],
    [/^Última atualização: (.+)$/, 'Last update: $1', 'Última actualización: $1'],
  ];
  for (const [pattern, en, es] of replacements) {
    if (pattern.test(value)) return value.replace(pattern, language === 'en' ? en : es);
  }
  return value;
}

export function translateUiText(value: string, language: SiteLanguage) {
  if (language === 'pt-BR' || !value) return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, leading, core, trailing] = match;
  const exact = dictionary[core]?.[language];
  return `${leading}${exact ?? translateDynamic(core, language)}${trailing}`;
}
