export function normalizeLanguage(value: unknown): SiteLanguage {
  return siteLanguages.includes(value as SiteLanguage) ? (value as SiteLanguage) : 'pt-BR';
}

export function localeForLanguage(language: SiteLanguage) {
  return language === 'en' ? 'en-US' : language === 'es' ? 'es-ES' : 'pt-BR';
}

